<?php

declare(strict_types=1);

namespace Polymorph\Sdk\Routing;

/**
 * Зона, в которую расширение вешает маршруты.
 *
 * Расширение объявляет ТОЛЬКО зону. Префикс URI и префикс имени маршрута
 * подставляет хост из id расширения, поэтому выйти за свою поверхность
 * или занять имя маршрута ядра нечем — проверять это отдельным классом
 * ограничений больше не нужно.
 */
enum ZoneKind: string
{
    /** Публичное API расширения. */
    case API = 'api';

    /** Админское API расширения (требует аутентификации). */
    case ADMIN_API = 'admin-api';

    /** Web-страницы расширения. */
    case WEB = 'web';
}
